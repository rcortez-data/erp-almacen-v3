# Programa: Ejemplo de caracteres especiales en Python

# Salto de linea \n
mensaje1 = "Hola\n\nMundo"
print(mensaje1)


# Tabulacion \t
# Imprimos una guia numerica para ver las posiciones
print("123412341234123412341234")
mensaje2 = "\t\tJuan Perez"
print(mensaje2)

# Comillas dentro de cadena
mensaje3 = "Ella dijo: \"Hola a todos\""
print(mensaje3)

# Barra invertida \
mensaje4 = "C:\\Usuarios\\Marce\\Documentos"
print(mensaje4)

# Cadenas crudas (raw string) r

mensaje5 = r"C:\Usuarios\Marce\Documentos"
print(mensaje5)
