print('*** Ciclo For ***')

print("Recorremos los caracteres de una cadena:")
cadena = 'Hola Mundo'
# Iteramos los caracteres
for letra in cadena:
    print(letra, end=' ')

print("\n\nRecorremos la lista de frutas:")  # Salto de línea entre los dos bucles for
frutas = ['Platano', 'Fresa', 'Mango']
# Iteramos las frutas
for fruta in frutas:
    print(fruta, end=' ')
